def test_npm_no_lockfile_404_recorded_as_unscanned_not_silent(
    tmp_path, monkeypatch
):
    """fix-npm-no-lockfile-404-silent-drop: a 404'd/unreachable npm package on
    the no-lockfile (package.json) path must be recorded in marker_skipped
    (``npm_doc_not_found``) — not silently dropped. The v0.6.0
    ``_resolve_npm_dist_tag`` returned ``None`` when the registry doc 404'd and
    ``_resolve_npm_package_json`` did ``if not version: continue`` with NO
    ``marker_skipped`` signal (unlike PyPI's ``_walk_pypi``), so a yanked /
    unpublished package — itself a supply-chain red flag — vanished from both
    ``packages`` and ``marker_skipped``: a silent under-scan. The fix threads
    ``marker_skipped`` into the npm no-lockfile walk and appends a
    ``npm_doc_not_found`` marker, mirroring PyPI's ``_walk_pypi`` handling."""
    import requests

    from promptaudit.resolver import MarkerSkipped, resolve

    (tmp_path / "package.json").write_text(
        json.dumps({"name": "app", "dependencies": {"ghost-dep": "^1.2.0"}}),
        encoding="utf-8",
    )

    def _fake_get(self, url, *a, **kw):
        # The whole-package registry doc 404s for every URL (yanked /
        # unpublished / unreachable) — _resolve_npm_dist_tag returns None.
        return _FakeResponse(status_code=404)

    monkeypatch.setattr(requests.Session, "get", _fake_get)

    skipped: list[MarkerSkipped] = []
    pkgs = list(resolve(tmp_path, marker_skipped=skipped))

    ghost = [p for p in pkgs if p.name == "ghost-dep"]
    # Hard signal: the 404'd package must NOT be resolved to a version.
    assert not ghost, f"a 404'd npm package must not be resolved; got {ghost}"
    # And it must be surfaced as a coverage gap, not dropped silently (the
    # v0.6.0 path left it in NEITHER packages NOR marker_skipped).
    ghost_skipped = [ms for ms in skipped if ms.name == "ghost-dep"]
    assert ghost_skipped, (
        "a 404'd npm package on the no-lockfile path must surface as a coverage "
        "gap (marker_skipped/npm_doc_not_found), not vanish silently; skipped "
        f"was {skipped}"
    )
    assert ghost_skipped[0].marker == "npm_doc_not_found", ghost_skipped[0].marker
    assert ghost_skipped[0].ecosystem == "npm", ghost_skipped[0].ecosystem
