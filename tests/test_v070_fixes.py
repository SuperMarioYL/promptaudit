"""v0.7.0 regression tests — three correctness fixes.

Each test is written to be RED on the v0.6.0 baseline (the bug class it
targets) and GREEN after the fix:

* ``test_hashed_requirements_txt_resolves_dep_not_zero`` —
  fix-requirements-hashes-silent-drop: a ``pip-compile`` /
  ``--require-hashes`` requirements.txt (``name==1.0.0 --hash=sha256:...``
  per logical line, the DevSecOps pinned-requirements format) raised
  ``InvalidRequirement`` on every hashed line and was swallowed by
  ``except Exception: continue`` → ZERO deps resolved → exit 0, a silent
  full-tree under-scan / false-clean. RED: zero deps. GREEN: foo resolves.
* ``test_npm_range_no_match_does_not_resolve_to_latest`` —
  fix-npm-range-no-match-resolves-latest: an npm range spec (``^1.2.0``) with
  NO satisfying published version fell back to ``dist-tags.latest`` (necessarily
  OUTSIDE the range) and was fetched + scanned, false-passing the gate. RED:
  audits 2.0.0. GREEN: surfaces as ``range_unsatisfiable:<spec>`` coverage gap.
* ``test_npm_no_lockfile_404_recorded_as_unscanned_not_silent`` —
  fix-npm-no-lockfile-404-silent-drop: a 404'd/unreachable npm package on the
  no-lockfile path returned ``None`` from ``_resolve_npm_dist_tag`` and was
  silently ``continue``-d with no ``marker_skipped`` signal, vanishing from
  both ``packages`` and the coverage report. RED: in neither. GREEN:
  ``npm_doc_not_found`` coverage gap.
"""

