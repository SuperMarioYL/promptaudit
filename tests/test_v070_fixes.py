# Fix 1 — fix-requirements-hashes-silent-drop
# --------------------------------------------------------------------------- #


def test_hashed_requirements_txt_resolves_dep_not_zero(tmp_path, monkeypatch):
    """fix-requirements-hashes-silent-drop: a pip-compile /
    ``--require-hashes`` requirements.txt (``name==1.0.0 --hash=sha256:...``
    per logical line, the DevSecOps pinned-requirements format) must resolve
    its dep — not ZERO. The v0.6.0 pre-processing only stripped ``#`` comments
    and ``--`` flag lines, NOT ``--hash`` tokens, so every hashed line raised
    ``InvalidRequirement`` and was swallowed by ``except Exception: continue``
    → zero deps resolved → exit 0, a silent full-tree under-scan / false-clean
    on the core surface. The fix joins backslash-continued physical lines and
    strips ``--hash`` / ``--hash=`` tokens before ``Requirement(line)`` parses
    the PEP 508 name@spec (mirrors how ``--`` flags are already stripped)."""
    import requests

    from promptaudit.resolver import resolve

    # pip-compile --generate-hashes output: one logical requirement per line,
    # --hash options spread across backslash-continued physical lines (the
    # canonical pinned-requirements format this tool's commercial audience
    # uses). A trailing-backslash continuation + inline --hash tokens both
    # break Requirement(line) on the v0.6.0 path.
    (tmp_path / "requirements.txt").write_text(
        "# This file is autogenerated by pip-compile\n"
        "# To update, run:\n"
        "#    pip-compile --generate-hashes\n"
        "foo==1.0.0 \\\n"
        "    --hash=sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa \\\n"
        "    --hash=sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb\n",
        encoding="utf-8",
    )

    def _fake_get(self, url, *a, **kw):
        # Exact-pin lookup: _walk_pypi fetches /pypi/foo/1.0.0/json.
        if url.endswith("/foo/1.0.0/json"):
            return _FakeResponse(
                status_code=200,
                payload={
                    "info": {"version": "1.0.0", "requires_dist": None},
                    "releases": {"1.0.0": []},
                },
            )
        return _FakeResponse(status_code=404)

    monkeypatch.setattr(requests.Session, "get", _fake_get)

    pkgs = list(resolve(tmp_path))
    foo = [p for p in pkgs if p.name == "foo"]
    assert foo, (
        "the hashed requirements.txt must resolve foo (pip-compile / "
        "--require-hashes format); got ZERO deps — the v0.6.0 path dropped "
        f"every --hash line as InvalidRequirement. resolved: {pkgs}"
    )
    assert foo[0].version == "1.0.0", foo[0].version
    assert foo[0].ecosystem == "pypi", foo[0].ecosystem


