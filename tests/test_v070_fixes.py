def test_npm_range_no_match_does_not_resolve_to_latest(tmp_path, monkeypatch):
    """fix-npm-range-no-match-resolves-latest: an npm range spec with NO
    satisfying published version must NOT fall back to ``dist-tags.latest``
    (which is necessarily OUTSIDE the range, else it would itself be a
    candidate) and be audited. The v0.6.0 ``_resolve_npm_max_satisfying``
    returned ``dist-tags.latest`` when ``candidates`` was empty, so the
    no-lockfile walk fetched + scanned an un-installable version and, if clean,
    false-passed the CI gate. The fix mirrors PyPI's ``_PinFailed`` sentinel:
    surface the dep as a coverage gap (``range_unsatisfiable:<spec>``) instead.
    This is the npm-side analog of v0.6.0's
    ``fix-tilde-pin-lookup-failure-resolves-latest`` (PyPI ``~=`` side)."""
    import requests
    from packaging.version import Version

    from promptaudit.resolver import MarkerSkipped, _npm_range_matcher, resolve

    (tmp_path / "package.json").write_text(
        json.dumps({"name": "app", "dependencies": {"leftpad": "^1.2.0"}}),
        encoding="utf-8",
    )

    def _fake_get(self, url, *a, **kw):
        # Full registry document — only 0.9.0 and 2.0.0 published, NEITHER
        # satisfies ^1.2.0 (>=1.2.0,<2.0.0). dist-tags.latest=2.0.0 is the
        # out-of-range bait the v0.6.0 fallback would audit.
        if url.endswith("/leftpad"):
            return _FakeResponse(
                status_code=200,
                payload={
                    "dist-tags": {"latest": "2.0.0"},
                    "versions": {"0.9.0": {}, "2.0.0": {}},
                },
            )
        # Bait version doc — if the bug is present, the resolver fetches
        # /leftpad/2.0.0 (the out-of-range latest) and yields leftpad@2.0.0.
        if url.endswith("/leftpad/2.0.0"):
            return _FakeResponse(status_code=200, payload={"dependencies": {}})
        return _FakeResponse(status_code=404)

    monkeypatch.setattr(requests.Session, "get", _fake_get)

    skipped: list[MarkerSkipped] = []
    pkgs = list(resolve(tmp_path, marker_skipped=skipped))

    leftpad = [p for p in pkgs if p.name == "leftpad"]
    # Hard signal: leftpad must NOT be resolved to the out-of-range 2.0.0.
    assert not leftpad, (
        "leftpad ^1.2.0 with no satisfying published version must NOT resolve "
        "to the out-of-range dist-tags.latest 2.0.0; the v0.6.0 fallback would "
        f"audit an un-installable version. resolved: {leftpad}"
    )
    leftpad_versions = {p.version for p in pkgs if p.name == "leftpad"}
    assert "2.0.0" not in leftpad_versions, (
        f"2.0.0 must NOT be audited for a ^1.2.0 range nothing satisfies; "
        f"got versions {leftpad_versions}"
    )
    # And it must be surfaced as a coverage gap, not dropped silently.
    leftpad_skipped = [ms for ms in skipped if ms.name == "leftpad"]
    assert leftpad_skipped, (
        "leftpad range-unsatisfiable must surface as a coverage gap "
        f"(marker_skipped); skipped was {skipped}"
    )
    assert leftpad_skipped[0].marker == "range_unsatisfiable:^1.2.0", (
        leftpad_skipped[0].marker
    )
    assert leftpad_skipped[0].ecosystem == "npm", leftpad_skipped[0].ecosystem
    # Sanity: 2.0.0 is genuinely outside ^1.2.0 (and 1.9.9 would satisfy but
    # is not published), so auditing 2.0.0 would be a false-clean on the
    # "audit the version you actually install" promise.
    matcher = _npm_range_matcher("^1.2.0")
    assert not matcher(Version("2.0.0"))
    assert matcher(Version("1.9.9"))


